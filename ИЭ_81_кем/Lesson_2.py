#глупый калькулятор -
num1 = int(input("Введите первое число - "))
num2 = int(input("Введите второе число - "))

user_choice = input(
    "Выберите действие\n"
    "1 - сложение\n"
    "2 - вычитание\n"
    "3 - деление\n"
    "4 - умножение\n"
    "b - ошибка\n"
)

if user_choice == "1":
    print(num1 + num2)
elif user_choice == "2":
    print(num1 - num2)
elif user_choice == "3":
    if num2 == 0:
        print("Ошибка: на ноль делить нельзя")
    else:
        print(num1 / num2)
elif user_choice == "4":
    print(num1 * num2)
elif user_choice == "b":
    print("Ошибка")
else:
    print("Неизвестное действие")

