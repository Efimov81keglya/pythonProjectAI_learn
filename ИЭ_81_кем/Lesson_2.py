# для определения типов шасси и набора
# датчиков необходимых роботу для передвижения по разным поверхностям
print("=== Конфигуратор робота ===\n")

surface = input("По какой поверхности будет ездить робот?\n"
                "1 - ровная дорога (асфальт, плитка)\n"
                "2 - бездорожье (песок, грязь, снег)\n"
                "3 - пересечённая местность (камни, ступеньки)\n"
                "4 - водная поверхность\n"
                "ваш выбор - ")

if surface == "1":
    road = input("Дорога сухая или мокрая? (сухая/мокрая) - ")
    if road == "сухая":
        speed = input("Нужна высокая скорость? (да/нет) - ")
        if speed == "да":
            chassis = "колёсное шасси (спортивные колёса)"
            sensors = "энкодеры, лидар"
        else:
            chassis = "колёсное шасси (4 колеса)"
            sensors = "энкодеры, ультразвуковые датчики"
    elif road == "мокрая":
        chassis = "колёсное шасси с протектором"
        sensors = "энкодеры, гироскоп (контроль заноса)"
    else:
        chassis = "не определено"
        sensors = "не определены"
        print("Ошибка: введите 'сухая' или 'мокрая'")

elif surface == "2":
    ground = input("Какое бездорожье? (песок/грязь/снег) - ")
    if ground == "песок":
        chassis = "гусеничное шасси с широкими гусеницами"
        sensors = "датчики буксования, GPS"
    elif ground == "грязь":
        deep = input("Грязь глубокая? (да/нет) - ")
        if deep == "да":
            chassis = "гусеницы с высоким клиренсом"
            sensors = "датчики погружения, гироскоп, GPS"
        else:
            chassis = "стандартные гусеницы"
            sensors = "гироскоп, GPS"
    elif ground == "снег":
        frost = input("Температура ниже -20? (да/нет) - ")
        if frost == "да":
            chassis = "гусеницы снегоходного типа"
            sensors = "обогреваемые камеры, ИК-датчики, GPS"
        else:
            chassis = "гусеницы снегоходного типа"
            sensors = "камеры, ИК-датчики, GPS"
    else:
        chassis = "не определено"
        sensors = "не определены"
        print("Ошибка: выберите песок, грязь или снег")

elif surface == "3":
    obstacle = input("Какие препятствия? (камни/ступеньки) - ")
    if obstacle == "камни":
        chassis = "шагающее шасси (4 ноги)"
        sensors = "лидар, камеры глубины, датчики касания, гироскоп"
    elif obstacle == "ступеньки":
        height = input("Высота ступенек больше 20 см? (да/нет) - ")
        if height == "да":
            chassis = "шагающее шасси (6 ног)"
            sensors = "лидар, гироскоп, датчики усилия в суставах"
        else:
            chassis = "гибридное (колёса + ноги)"
            sensors = "камеры, гироскоп, энкодеры"
    else:
        chassis = "не определено"
        sensors = "не определены"
        print("Ошибка: выберите камни или ступеньки")

elif surface == "4":
    water = input("Вода спокойная или с волнами? (спокойная/волны) - ")
    if water == "спокойная":
        chassis = "амфибия (колёса + водомёт)"
        sensors = "сонар, GPS, датчик протечки"
    elif water == "волны":
        chassis = "платформа со стабилизацией"
        sensors = "сонар, гироскоп, GPS, датчик протечки"
    else:
        chassis = "не определено"
        sensors = "не определены"
        print("Ошибка: введите 'спокойная' или 'волны'")

else:
    chassis = "не определено"
    sensors = "не определены"
    print("Ошибка: выберите число от 1 до 4")

print("\n=== Результат ===")
print("Шасси:", chassis)
print("Датчики:", sensors)
